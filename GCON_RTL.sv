// -----------------------------------------------------------------------------
// Sequential SubBytes block: substitutes one byte per clock for 16 clocks.
// -----------------------------------------------------------------------------

module AES_SBOX_SEQ (
    input  wire         clk,
    input  wire         reset,
    input  wire         start,
    input  wire [127:0] in_block,
    output reg  [127:0] out_block,
    output reg          done
);

// running is high while the module is substituting bytes.
// idx selects which byte of the 128-bit input block is currently being read.
(* preserve = 1 *) reg        running;
(* preserve = 1 *) reg [3:0]  idx;

// s_in is the current byte sent into the S-box.
// s_out is the substituted byte returned from the S-box.
(* keep = 1 *) wire [7:0] s_in;
wire [7:0] s_out;

// One S-box ROM is reused for all 16 bytes.  This saves hardware compared to
// using 16 S-boxes in parallel, at the cost of extra clock cycles.
AES_SBOX_ROM rom (.a(s_in), .c(s_out));

// Select one byte per clock from MSB to LSB.
assign s_in = in_block[127 - (idx * 8) -: 8];

always @(posedge clk or posedge reset) begin
    if (reset) begin
        idx       <= 4'd0;
        done      <= 1'b0;
        running   <= 1'b0;
        out_block <= 128'd0;
    end else begin
        done <= 1'b0;

        if (start && !running) begin
            // Begin a new 16-byte substitution pass.
            idx     <= 4'd0;
            running <= 1'b1;
        end else if (running) begin
            // Store the substituted byte back into the same byte position.
            out_block[127 - (idx * 8) -: 8] <= s_out;

            if (idx == 4'd15) begin
                // Last byte has been written.  Raise done for one clock.
                running <= 1'b0;
                done    <= 1'b1;
            end else begin
                idx <= idx + 4'd1;
            end
        end
    end
end
endmodule

