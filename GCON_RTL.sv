
// Module order in this file:
//   1. AES128_updated_new : top module and main finite state machine (FSM)
//   2. AES_SBOX_ROM       : AES S-box lookup table
//   3. AES_SBOX_SEQ       : sequential SubBytes engine
//   4. AES_MIXCOL_SEQ     : sequential MixColumns engine
//   5. AES_KEYEXP_SEQ     : AES-128 key expansion engine
//
// Design idea:
//   AES normally performs ten encryption rounds.  A fully parallel design may
//   instantiate many round blocks at the same time.  This design instead reuses
//   one set of hardware blocks under FSM control.  Reuse lowers area and reduces
//   simultaneous switching activity, which is useful for low-power FPGA/IoT
//   applications.
//
// Handshake:
//   - Apply plaintext and key.
//   - Pulse start high for one clock.
//   - The core asserts busy while encryption is running.
//   - When done becomes high, ciphertext is valid.
//
// Notes:
//   - <= is nonblocking assignment, used inside clocked always blocks.
//   - = is blocking assignment, used inside combinational functions/logic.
//   - [127 - (idx * 8) -: 8] means "select 8 bits starting from bit
//     127-(idx*8) and counting downward".
//   - Attributes such as keep/preserve help FPGA tools retain useful signal
//     names for debugging and RTL/netlist viewing. They do not change the AES
//     algorithm.
// -----------------------------------------------------------------------------


